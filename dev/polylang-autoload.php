<?php
/**
 * Write vendor/autoload.php (and the loader lists) for a Polylang checkout taken from GitHub, which ships without
 * Composer's vendor folder: a classmap of src/, as Composer would build it. Local development only.
 *
 * Usage: php dev/polylang-autoload.php <path-to-polylang>
 *
 * @package its-rossellini-dev
 */

if ( PHP_SAPI !== 'cli' ) {
	exit( 1 );
}

$dir = rtrim( (string) ( $argv[1] ?? '' ), '/\\' );
if ( ! is_dir( $dir . '/src' ) ) {
	fwrite( STDERR, "No src/ folder in {$dir}\n" );
	exit( 1 );
}

$skip  = array( T_WHITESPACE, T_COMMENT, T_DOC_COMMENT );
$kinds = array( T_CLASS, T_INTERFACE, T_TRAIT );
if ( defined( 'T_ENUM' ) ) {
	$kinds[] = T_ENUM;
}

$map   = array();
$files = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $dir . '/src', FilesystemIterator::SKIP_DOTS ) );
foreach ( $files as $file ) {
	if ( 'php' !== $file->getExtension() ) {
		continue;
	}
	$tokens    = token_get_all( (string) file_get_contents( $file->getPathname() ) );
	$count     = count( $tokens );
	$namespace = '';
	for ( $i = 0; $i < $count; $i++ ) {
		if ( ! is_array( $tokens[ $i ] ) ) {
			continue;
		}
		if ( T_NAMESPACE === $tokens[ $i ][0] ) {
			$namespace = '';
			for ( $j = $i + 1; $j < $count; $j++ ) {
				if ( ';' === $tokens[ $j ] || '{' === $tokens[ $j ] ) {
					break;
				}
				if ( is_array( $tokens[ $j ] ) && ! in_array( $tokens[ $j ][0], $skip, true ) ) {
					$namespace .= $tokens[ $j ][1];
				}
			}
			continue;
		}
		if ( ! in_array( $tokens[ $i ][0], $kinds, true ) ) {
			continue;
		}
		// Not "Foo::class" and not "new class".
		$p = $i - 1;
		while ( $p >= 0 && is_array( $tokens[ $p ] ) && in_array( $tokens[ $p ][0], $skip, true ) ) {
			--$p;
		}
		if ( $p >= 0 && is_array( $tokens[ $p ] ) && in_array( $tokens[ $p ][0], array( T_DOUBLE_COLON, T_NEW ), true ) ) {
			continue;
		}
		$n = $i + 1;
		while ( $n < $count && is_array( $tokens[ $n ] ) && in_array( $tokens[ $n ][0], $skip, true ) ) {
			++$n;
		}
		if ( $n < $count && is_array( $tokens[ $n ] ) && T_STRING === $tokens[ $n ][0] ) {
			$class                       = ltrim( $namespace . '\\' . $tokens[ $n ][1], '\\' );
			$path                        = substr( str_replace( '\\', '/', $file->getPathname() ), strlen( str_replace( '\\', '/', $dir ) ) );
			$map[ strtolower( $class ) ] = $path;
		}
	}
}
ksort( $map );

$lines = array();
foreach ( $map as $class => $path ) {
	$lines[] = "\t" . var_export( $class, true ) . ' => ' . var_export( $path, true ) . ',';
}
$php = "<?php\n// Generated by dev/polylang-autoload.php for local development (classmap of src/).\n"
	. "\$its_pll_classmap = array(\n" . implode( "\n", $lines ) . "\n);\n"
	. "spl_autoload_register(\n\tstatic function ( \$class ) use ( \$its_pll_classmap ) {\n"
	. "\t\t\$key = strtolower( ltrim( \$class, '\\\\' ) );\n"
	. "\t\tif ( isset( \$its_pll_classmap[ \$key ] ) ) {\n\t\t\trequire dirname( __DIR__ ) . \$its_pll_classmap[ \$key ];\n\t\t}\n\t}\n);\n";

if ( ! is_dir( $dir . '/vendor' ) ) {
	mkdir( $dir . '/vendor', 0777, true );
}
file_put_contents( $dir . '/vendor/autoload.php', $php );

// Loader lists the release build writes (src/modules/module-build.php, src/integrations/integration-build.php).
foreach ( array(
	'modules'      => 'module',
	'integrations' => 'integration',
) as $folder => $type ) {
	$loaders = glob( "{$dir}/src/{$folder}/*/load.php" ) ?: array();
	$list    = '';
	foreach ( $loaders as $loader ) {
		$list .= "\t" . var_export( basename( dirname( $loader ) ), true ) . ",\n";
	}
	file_put_contents( "{$dir}/src/{$folder}/{$type}-build.php", "<?php\n// Generated by dev/polylang-autoload.php.\nreturn array(\n{$list});\n" );
}
echo 'Polylang autoload: ' . count( $map ) . " classes.\n";
